#!/usr/bin/env node
// Generates the translated landing pages from docs/index.html and site/<locale>.ftl; --check fails when they are stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes('--check');
const source = fs.readFileSync(path.join(root, 'docs/index.html'), 'utf8');
const ogLocales = { ja: 'ja_JP', 'zh-Hans': 'zh_CN', 'zh-Hant': 'zh_TW' };
const plain = html => html.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&gt;/g, '>').replace(/&lt;/g, '<');

// Each message's comment is its English source, so editing the English invalidates the translation.
function parse(ftl) {
  const strings = {};
  let english = null;
  for (const line of ftl.split('\n')) {
    const message = line.match(/^[a-z][a-z0-9_-]* = (.*)$/);
    if (line.startsWith('# ')) english = line.slice(2);
    else if (message && english !== null) {
      strings[english] = message[1];
      english = null;
    } else if (line && !line.startsWith('###')) throw new Error(`invalid line: ${line}`);
  }
  return strings;
}

function swap(text, from, to) {
  if (!text.includes(from)) throw new Error(`docs/index.html no longer contains: ${from}`);
  return text.replace(from, () => to);
}

function render(lang, strings) {
  const dir = lang.toLowerCase();
  const used = new Set(), missing = new Set(), stashed = [], faq = [];
  const t = text => {
    const key = text.trim();
    if (key in strings) used.add(key);
    else missing.add(key);
    return strings[key] ?? key;
  };
  const attr = text => t(text).replaceAll('"', '&quot;');
  // Translated markup is set aside so later passes cannot match the anchors and attributes inside it.
  const stash = html => (stashed.push(html), `@@${stashed.length - 1}@@`);
  const url = `https://jayjay.hewig.dev/${dir}/`;

  let page = [
    ['<html lang="en">', `<html lang="${lang}">`],
    ['<head>', `<head>\n  <!-- Generated by \`just site\` from docs/index.html and site/${lang}.ftl. -->`],
    ['<body>', '<body class="cjk">'],
    ['<link rel="canonical" href="https://jayjay.hewig.dev/">', `<link rel="canonical" href="${url}">`],
    ['<meta property="og:type" content="website">', `<meta property="og:type" content="website">\n  <meta property="og:locale" content="${ogLocales[lang]}">`],
    ['<meta property="og:url" content="https://jayjay.hewig.dev/">', `<meta property="og:url" content="${url}">`],
    [' aria-current="page"', ''],
    [`hreflang="${lang}">`, `hreflang="${lang}" aria-current="page">`],
    ['href="./"', 'href="../"'],
  ].reduce((text, [from, to]) => swap(text, from, to), source);

  page = page
    .replace(/<title>(.*?)<\/title>/, (m, x) => `<title>${t(x)}</title>`)
    .replace(/(<meta name="(?:description|keywords)"\s+content=")([^"]*)/g, (m, o, x) => o + attr(x))
    .replace(/((?:og|twitter):(?:title|description|image:alt)" content=")([^"]*)/g, (m, o, x) => o + attr(x))
    .replace(/"description": ("JayJay is a native GUI.*"),/, (m, x) => `"description": ${JSON.stringify(t(JSON.parse(x)))},`);

  page = page
    .replace(/<div class="lang-menu"[\s\S]*?<\/div>/, stash)
    .replace(/<a class="post-card"[\s\S]*?<\/a>/g, m => stash(m.replace('<a class="post-card"', '<a class="post-card" lang="en"')))
    .replace(/<summary>(.*?)<\/summary>(\s*)<p>(.*?)<\/p>/g, (m, q, gap, a) => {
      faq.push([plain(t(q)), plain(t(a))]);
      return `<summary>${stash(t(q))}</summary>${gap}<p>${stash(t(a))}</p>`;
    })
    .replace(/(<(h1|h2|h3|p)\b[^>]*>)([\s\S]*?)(<\/\2>)/g, (m, open, tag, x, close) => (x.startsWith('@@') ? m : open + stash(t(x)) + close))
    .replace(/<div class="eyebrow">(.*?)<\/div>/g, (m, x) => `<div class="eyebrow">${t(x)}</div>`)
    .replace(/(<a\b[^>]*>)([^<]+)(<\/a>)/g, (m, open, x, close) => open + t(x) + close)
    .replace(/<li><span>(.*?)<\/span>/g, (m, x) => `<li><span>${t(x)}</span>`)
    .replace(/<kbd>(Space|Click)<\/kbd>/g, (m, x) => `<kbd>${t(x)}</kbd>`)
    .replace(/(<button[^>]*>\s*(?:<svg.*?<\/svg>\s*)?)([^<]+?)(\s*<\/button>)/gs, (m, open, x, close) => open + t(x) + close)
    .replace(/<span class="c"># (.*?)<\/span>/g, (m, x) => `<span class="c"># ${t(x)}</span>`)
    .replace(/\b(alt|aria-label)="([^"]+)"/g, (m, name, x) => `${name}="${attr(x)}"`)
    .replace(/data-captions="([^"]+)"/g, (m, x) => `data-captions="${x.split('|').map(step => {
      const [, at, text] = step.match(/^([\d.]+ )?(.*)$/);
      return (at ?? '') + attr(text);
    }).join('|')}"`)
    .replace(/(\s*<div class="posts">)/, m => `\n      <p class="sec-sub">${t('Articles are in English.')}</p>${m}`)
    .replace(/@@(\d+)@@/g, (m, i) => stashed[i])
    .replace(/"mainEntity": \[[\s\S]*?\n    \]/, () => {
      const entries = faq.map(([q, a]) => `      { "@type": "Question", "name": ${JSON.stringify(q)}, "acceptedAnswer": { "@type": "Answer", "text": ${JSON.stringify(a)} } }`);
      return `"mainEntity": [\n${entries.join(',\n')}\n    ]`;
    })
    .replace(/\b(href|src|poster)="(?!https?:|#|\.\.\/)([^"]+)"/g, (m, name, target) => `${name}="../${target}"`)
    .replace(/href="\.\.\/(guide\.html|blog\/|privacy\.html)/g, (m, target) => `hreflang="en" href="../${target}`);

  const body = page.slice(page.indexOf('<body')).replace(/<!--[\s\S]*?-->|<(script|pre|code|kbd)\b[\s\S]*?<\/\1>|<a class="post-card"[\s\S]*?<\/a>/g, '');
  for (const [, text] of body.matchAll(/>([^<]*[A-Za-z]{3,} [a-z]{2,} [a-z]{2,}[^<]*)</g)) missing.add(text.trim());
  const unused = Object.keys(strings).filter(key => !used.has(key));
  return { page, missing: [...missing], unused };
}

let failed = false;
const fail = message => {
  console.error(message);
  failed = true;
};

for (const lang of Object.keys(ogLocales)) {
  const file = `${lang}.ftl`;
  const { page, missing, unused } = render(lang, parse(fs.readFileSync(path.join(root, 'site', file), 'utf8')));
  for (const key of missing) fail(`site/${file}: missing translation: ${key}`);
  for (const key of unused) fail(`site/${file}: unused translation: ${key}`);
  if (failed) continue;
  const output = path.join(root, 'docs', lang.toLowerCase(), 'index.html');
  if (!check) {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, page);
  } else if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== page) {
    fail(`${path.relative(root, output)} is stale; run just site`);
  }
}
process.exit(failed ? 1 : 0);
