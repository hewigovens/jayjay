impl ShortcutCommand {
    pub fn all() -> &'static [Self] {
        &ALL
    }

    pub fn from_id(id: &str) -> Option<Self> {
        Self::all()
            .iter()
            .copied()
            .find(|command| command.id() == id)
    }
}

