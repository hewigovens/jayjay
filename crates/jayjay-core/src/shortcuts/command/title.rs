use jayjay_i18n::{menu, merge, palette, repo, shortcuts};

use super::ShortcutCommand;

impl ShortcutCommand {
    pub fn title(self) -> String {
        match self {
            Self::AppOpenRepository => repo::open_repository(),
            Self::AppKeyboardShortcuts => menu::keyboard_shortcuts(),
            Self::AppZoomIn => menu::zoom_in(),
            Self::AppZoomOut => menu::zoom_out(),
            Self::AppResetZoom => menu::reset_zoom(),
            Self::AppSettings => menu::settings_ellipsis(),
            Self::AppQuit => menu::quit_jayjay(),
            Self::AppCloseWindow => shortcuts::close_window(),
            Self::RepoCommandPalette => menu::command_palette(),
            Self::RepoRefresh => repo::refresh(),
            Self::RepoToggleSidebar => palette::hide_show_sidebar(),
            Self::RepoUndoLastOperation => menu::undo_last_operation(),
            Self::RepoFilterByRevset => shortcuts::filter_by_revset(),
            Self::RepoBookmarkManager => menu::bookmark_manager(),
            Self::RepoOverview => menu::repo_overview(),
            Self::RepoShowInFileManager => palette::show_in_file_manager(),
            Self::RepoFindInDiff => palette::find_in_diff(),
            Self::RepoFetch => menu::pull(),
            Self::RepoPush => repo::git_push(),
            Self::RepoNewWorkspace => menu::new_workspace_ellipsis(),
            Self::RepoImportPullRequest => menu::new_workspace_from_pull_request_ellipsis(),
            Self::RepoRebaseOntoTrunk => menu::rebase_onto_trunk(),
            Self::RepoBisect => repo::bisect(),
            Self::RepoCleanUpStaleBookmarks => palette::clean_up_stale_bookmarks(),
            Self::RepoToggleSideBySide => palette::toggle_side_by_side_diff_title(),
            Self::RepoToggleIgnoreWhitespace => palette::toggle_ignore_whitespace(),
            Self::RepoToggleTreeFileList => palette::toggle_tree_file_list(),
            Self::RepoNewChange => menu::new_change_on_top(),
            Self::RepoEditChange => menu::edit_modify_this_change(),
            Self::RepoDescribeChange => menu::describe_ellipsis(),
            Self::RepoSquashChange => menu::squash_into_parent(),
            Self::RepoNewBookmark => menu::create_bookmark_here_ellipsis(),
            Self::RepoShowEvolution => menu::show_evolution_ellipsis(),
            Self::RepoCopyDiffSelection => shortcuts::copy_diff_selection(),
            Self::RepoSwitchPane => shortcuts::switch_active_pane(),
            Self::RepoCyclePanes => shortcuts::cycle_focused_pane(),
            Self::RepoOpenContextMenu => shortcuts::open_selection_menu(),
            Self::OverviewFilterLanes => shortcuts::filter_overview_lanes(),
            Self::DiffEditorExpandAllFiles => shortcuts::expand_all_files(),
            Self::DiffEditorCollapseAllFiles => shortcuts::collapse_all_files(),
            Self::TextSaveFile => shortcuts::save_edited_file(),
            Self::TextSaveReviewNote => shortcuts::save_review_note(),
            Self::MergeAcceptLeft => merge::accept_left(),
            Self::MergeAcceptRight => merge::accept_right(),
            Self::MergePreviousConflict => shortcuts::previous_conflict(),
            Self::MergeNextConflict => shortcuts::next_conflict(),
            Self::ChangesAbandon => menu::abandon(),
            Self::ChangesNext => shortcuts::next_change(),
            Self::ChangesPrevious => shortcuts::previous_change(),
            Self::FilesNext => shortcuts::next_file(),
            Self::FilesPrevious => shortcuts::previous_file(),
            Self::FilesMarkReviewed => palette::mark_file_reviewed(),
            Self::DiffNextPreviousFileCard => shortcuts::next_previous_file_card(),
            Self::DiffCollapseExpandFileCard => shortcuts::collapse_expand_file_card(),
            Self::DiffToggleFileCard => shortcuts::toggle_file_card(),
        }
    }
}
