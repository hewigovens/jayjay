#[test]
fn sarif_projection_renders_markdown_report() {
    let (_fixture, repo) = fixture_repo();

    let projected = hunk(&repo, FormatFixture::SARIF);
    let projection = projected.projection.as_ref().expect("projection metadata");
    assert_eq!(projection.plugin_id, "sarif");
    assert_eq!(projection.render_kind, DiffRenderKind::Markdown);
    assert_eq!(projection.virtual_path, "results.sarif.md");
    let content = projected.new.content.as_deref().expect("projected content");
    assert!(content.contains("# SARIF Report"));
    assert!(content.contains("## Run 1: JayJay Security Scan"));
    assert!(content.contains("### JJ001: Shell command injection"));
    assert!(content.contains("- Level: `error`"));
    assert!(content.contains("- Location: `Sources/RepositoryActions.swift:88:17`"));
    assert!(content.contains("- Message: Quote or avoid shell interpolation for branch names."));
    assert!(!content.contains("\"runs\""));

    let raw = repo
        .show_file_raw("@", FormatFixture::SARIF)
        .expect("show raw SARIF");
    assert_eq!(
        raw.projection.as_ref().map(|p| p.mode),
        Some(DiffProjectionMode::Raw)
    );
    assert!(
        raw.new
            .content
            .as_deref()
            .is_some_and(|content| content.contains("\"runs\""))
    );
}

